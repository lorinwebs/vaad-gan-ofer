-- ציר זמן אירועים — להריץ פעם אחת ב-Supabase SQL Editor
create table if not exists public.gan_ofer_timeline (
  id bigint generated by default as identity primary key,
  event_date date,
  emoji text not null default '',
  title text not null,
  details text not null default '',
  sort_order int not null default 0,
  updated_at timestamptz not null default now()
);

alter table public.gan_ofer_timeline enable row level security;

drop policy if exists "gan_ofer_timeline anon read" on public.gan_ofer_timeline;
drop policy if exists "gan_ofer_timeline anon write" on public.gan_ofer_timeline;
create policy "gan_ofer_timeline anon read" on public.gan_ofer_timeline
  for select to anon using (true);
create policy "gan_ofer_timeline anon write" on public.gan_ofer_timeline
  for all to anon using (true) with check (true);

alter publication supabase_realtime add table public.gan_ofer_timeline;

