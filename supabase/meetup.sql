create table if not exists public.gan_ofer_meetup_items (
  id bigint generated by default as identity primary key,
  sort_order int not null default 0,
  emoji text not null default '',
  name text not null,
  qty int not null default 1 check (qty > 0)
);

create table if not exists public.gan_ofer_meetup_claims (
  id bigint generated by default as identity primary key,
  item_id bigint not null references public.gan_ofer_meetup_items(id) on delete cascade,
  child_id bigint not null references public.gan_ofer_children(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint gan_ofer_meetup_claims_item_child_key unique (item_id, child_id)
);

create or replace function public.gan_ofer_meetup_check_qty()
returns trigger language plpgsql set search_path = public as $$
declare cap int;
begin
  select qty into cap from public.gan_ofer_meetup_items where id = new.item_id for update;
  if (select count(*) from public.gan_ofer_meetup_claims
      where item_id = new.item_id and child_id <> new.child_id) >= cap then
    raise exception 'item_full';
  end if;
  return new;
end $$;

drop trigger if exists gan_ofer_meetup_check_qty on public.gan_ofer_meetup_claims;
create trigger gan_ofer_meetup_check_qty
  before insert or update on public.gan_ofer_meetup_claims
  for each row execute function public.gan_ofer_meetup_check_qty();

alter table public.gan_ofer_meetup_items enable row level security;
alter table public.gan_ofer_meetup_claims enable row level security;

drop policy if exists "meetup items anon read" on public.gan_ofer_meetup_items;
create policy "meetup items anon read" on public.gan_ofer_meetup_items
  for select to anon using (true);
drop policy if exists "meetup claims anon all" on public.gan_ofer_meetup_claims;
create policy "meetup claims anon all" on public.gan_ofer_meetup_claims
  for all to anon using (true) with check (true);

alter publication supabase_realtime add table public.gan_ofer_meetup_items;
alter publication supabase_realtime add table public.gan_ofer_meetup_claims;

