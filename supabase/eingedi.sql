-- Karziya Family · נסיעה לעין גדי 12–14.11 — הרשמת משפחות
create table if not exists public.karziya_eingedi_rsvps (
  id bigint generated by default as identity primary key,
  family_name text not null,
  kids_count int not null check (kids_count >= 0 and kids_count <= 30),
  created_at timestamptz not null default now()
);

create index if not exists karziya_eingedi_rsvps_created_at_idx
  on public.karziya_eingedi_rsvps (created_at desc);

alter table public.karziya_eingedi_rsvps enable row level security;

drop policy if exists "karziya eingedi rsvps anon read" on public.karziya_eingedi_rsvps;
create policy "karziya eingedi rsvps anon read" on public.karziya_eingedi_rsvps
  for select to anon using (true);

drop policy if exists "karziya eingedi rsvps anon insert" on public.karziya_eingedi_rsvps;
create policy "karziya eingedi rsvps anon insert" on public.karziya_eingedi_rsvps
  for insert to anon with check (
    char_length(trim(family_name)) between 1 and 80
    and kids_count >= 0
    and kids_count <= 30
  );

drop policy if exists "karziya eingedi rsvps anon delete" on public.karziya_eingedi_rsvps;
create policy "karziya eingedi rsvps anon delete" on public.karziya_eingedi_rsvps
  for delete to anon using (true);

alter publication supabase_realtime add table public.karziya_eingedi_rsvps;
